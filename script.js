(function () {
  "use strict";

  var DAY_ORDER = ["MA", "TI", "KE", "TO", "PE"];
  var DAY_NAMES = {
    MA: "Maanantai",
    TI: "Tiistai",
    KE: "Keskiviikko",
    TO: "Torstai",
    PE: "Perjantai",
  };

  var courseSelect = document.getElementById("courseSelect");
  var prevBtn = document.getElementById("prevDay");
  var nextBtn = document.getElementById("nextDay");
  var dayLabel = document.getElementById("dayLabel");
  var searchBtn = document.getElementById("searchBtn");
  var resultEl = document.getElementById("result");

  var STORAGE_KEY = "onkomeillasplit:selectedCourseByDay";

  function loadSelections() {
    try {
      return JSON.parse(localStorage.getItem(STORAGE_KEY)) || {};
    } catch (e) {
      return {};
    }
  }

  function saveSelection(day, course) {
    try {
      var selections = loadSelections();
      selections[day] = course;
      localStorage.setItem(STORAGE_KEY, JSON.stringify(selections));
    } catch (e) {
      // localStorage unavailable (e.g. private browsing) - ignore.
    }
  }

  function toDate(iso) {
    var parts = iso.split("-");
    return new Date(Number(parts[0]), Number(parts[1]) - 1, Number(parts[2]));
  }

  function findCurrentPeriod(periods, today) {
    var match = null;
    for (var i = 0; i < periods.length; i++) {
      var p = periods[i];
      if (toDate(p.start) <= today && today <= toDate(p.end)) {
        match = p;
        break;
      }
    }
    if (match) return match;

    // Fall back to whichever period is chronologically closest to today.
    var best = null;
    var bestDistance = Infinity;
    for (var j = 0; j < periods.length; j++) {
      var p2 = periods[j];
      var start = toDate(p2.start);
      var end = toDate(p2.end);
      var distance;
      if (today < start) {
        distance = start - today;
      } else if (today > end) {
        distance = today - end;
      } else {
        distance = 0;
      }
      if (distance < bestDistance) {
        bestDistance = distance;
        best = p2;
      }
    }
    return best;
  }

  function currentDayIndex(today) {
    var jsDay = today.getDay(); // 0 = Sunday ... 6 = Saturday
    if (jsDay >= 1 && jsDay <= 5) return jsDay - 1;
    return 0; // default to Monday on weekends
  }

  var today = new Date();
  var period = findCurrentPeriod(DATA, today);
  var dayIndex = currentDayIndex(today);

  function populateDropdown() {
    courseSelect.innerHTML = "";
    var placeholder = document.createElement("option");
    placeholder.value = "";
    placeholder.textContent = "Valitse kurssi";
    placeholder.disabled = true;
    placeholder.selected = true;
    courseSelect.appendChild(placeholder);

    if (!period) return false;

    var day = DAY_ORDER[dayIndex];
    var courses = []
      .concat(period.split[day] || [])
      .concat(period.normal[day] || []);
    courses.sort(function (a, b) {
      return a.localeCompare(b, "fi");
    });

    for (var i = 0; i < courses.length; i++) {
      var opt = document.createElement("option");
      opt.value = courses[i];
      opt.textContent = courses[i];
      courseSelect.appendChild(opt);
    }

    var saved = loadSelections()[day];
    if (saved && courses.indexOf(saved) !== -1) {
      courseSelect.value = saved;
      return true;
    }
    return false;
  }

  function renderDayLabel() {
    dayLabel.textContent = DAY_NAMES[DAY_ORDER[dayIndex]];
  }

  function resetResult() {
    resultEl.textContent = "?";
    resultEl.className = "result";
  }

  function search() {
    if (!period) {
      resultEl.textContent = "?";
      resultEl.className = "result";
      return;
    }
    var course = courseSelect.value;
    if (!course) return;

    var day = DAY_ORDER[dayIndex];
    if ((period.split[day] || []).indexOf(course) !== -1) {
      resultEl.textContent = "SPLIT";
      resultEl.className = "result split";
    } else if ((period.normal[day] || []).indexOf(course) !== -1) {
      resultEl.textContent = "NORMAALI";
      resultEl.className = "result normal";
    } else {
      resultEl.textContent = "?";
      resultEl.className = "result";
    }
  }

  function goToDay(newIndex) {
    dayIndex = newIndex;
    renderDayLabel();
    var restored = populateDropdown();
    if (restored) {
      search();
    } else {
      resetResult();
    }
  }

  prevBtn.addEventListener("click", function () {
    goToDay((dayIndex + DAY_ORDER.length - 1) % DAY_ORDER.length);
  });

  nextBtn.addEventListener("click", function () {
    goToDay((dayIndex + 1) % DAY_ORDER.length);
  });

  courseSelect.addEventListener("change", function () {
    if (courseSelect.value) {
      saveSelection(DAY_ORDER[dayIndex], courseSelect.value);
    }
  });

  searchBtn.addEventListener("click", search);

  goToDay(dayIndex);
})();
